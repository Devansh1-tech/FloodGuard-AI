"""
reports.py — Generated Analytical Reports & Geospatial Artifact Deliverables
=============================================================================

Tracks persisted document reports (PDF, HTML, JSON) and spatial deliverables
(GeoTIFF flood masks, GeoJSON polygons, cartographic maps) generated per FloodEvent.
"""

from __future__ import annotations

import datetime
import uuid
from typing import TYPE_CHECKING, Optional
from sqlalchemy import BigInteger, DateTime, Enum as SQLEnum, ForeignKey, Index, String, Uuid
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import Base, UUIDMixin
from app.models.enums import ArtifactType, ReportType

if TYPE_CHECKING:
    from app.models.flood_event import FloodEvent


class GeneratedReport(Base, UUIDMixin):
    """
    Formal disaster assessment document generated by the reporting engine.
    """

    __tablename__ = "generated_reports"

    flood_event_id: Mapped[uuid.UUID] = mapped_column(
        Uuid,
        ForeignKey("flood_events.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    report_type: Mapped[ReportType] = mapped_column(
        SQLEnum(ReportType, native_enum=False),
        nullable=False,
        index=True,
    )
    report_path: Mapped[str] = mapped_column(String(512), nullable=False)
    format: Mapped[str] = mapped_column(String(50), default="JSON", nullable=False)  # JSON, PDF, HTML, CSV

    created_at: Mapped[datetime.datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.datetime.now(datetime.timezone.utc),
        nullable=False,
    )

    # Relationship
    flood_event: Mapped[FloodEvent] = relationship("FloodEvent", back_populates="reports")

    __table_args__ = (
        Index("ix_reports_event_type", "flood_event_id", "report_type"),
    )

    def __repr__(self) -> str:
        return f"<GeneratedReport id={self.id} type={self.report_type} format='{self.format}'>"


class GeneratedArtifact(Base, UUIDMixin):
    """
    Geospatial deliverable, raster layer, or audit log file generated by the pipeline.
    """

    __tablename__ = "generated_artifacts"

    flood_event_id: Mapped[uuid.UUID] = mapped_column(
        Uuid,
        ForeignKey("flood_events.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    artifact_type: Mapped[ArtifactType] = mapped_column(
        SQLEnum(ArtifactType, native_enum=False),
        nullable=False,
        index=True,
    )
    file_path: Mapped[str] = mapped_column(String(512), nullable=False)
    file_size: Mapped[Optional[int]] = mapped_column(BigInteger, nullable=True)  # File size in bytes
    checksum: Mapped[Optional[str]] = mapped_column(String(64), nullable=True)   # SHA-256 hash

    created_at: Mapped[datetime.datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.datetime.now(datetime.timezone.utc),
        nullable=False,
    )

    # Relationship
    flood_event: Mapped[FloodEvent] = relationship("FloodEvent", back_populates="artifacts")

    __table_args__ = (
        Index("ix_artifacts_event_type", "flood_event_id", "artifact_type"),
        Index("ix_artifacts_checksum", "checksum"),
    )

    def __repr__(self) -> str:
        return f"<GeneratedArtifact id={self.id} type={self.artifact_type} path='{self.file_path}'>"
